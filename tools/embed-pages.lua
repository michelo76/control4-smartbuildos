#!/usr/bin/env luajit
--- Embeds each WebView driver's page (www/app/index.html) in a Lua module.
---
--- Bench, 13 Nov 2026: on Control4 OS 4.3 a driver may not read its own
--- packaged files (`C4:FileSetDir("C4Z_ROOT")` answers "Restricted path
--- specified"), so a relay that read the page from the c4z answered /app with
--- 503. The page is therefore also compiled into the driver as a module, which
--- needs no file access. The c4z still ships www/app/index.html for Navigator's
--- controller:// route.
---
--- Run from the repository root:  luajit tools/embed-pages.lua [--check]
---   --check  exit 1 (and say which) when a module is stale, writing nothing.

local PAGES = {
  { dir = "drivers/smartbuildos-commissioning", module = "src/commissioning/page.lua" },
  { dir = "drivers/smartbuildos-daypart", module = "src/daypart/page.lua" },
  { dir = "drivers/smartbuildos-pin-lock", module = "src/pinlock/page.lua" },
  -- VenueFlow ships two pages (operator and Installer Studio), built from
  -- ui/venueflow by tools/venueflow-ui.py.
  { dir = "drivers/smartbuildos-venueflow", module = "src/venueflow/page_app.lua" },
  { dir = "drivers/smartbuildos-venueflow", module = "src/venueflow/page_studio.lua", page = "www/studio/index.html" },
}

local HEADER = "-- GENERATED by tools/embed-pages.lua from %s. Do not edit;\n"
  .. "-- run `make embed-pages` after changing the page.\n"

local function read(path)
  local f = assert(io.open(path, "rb"), "cannot read " .. path)
  local s = f:read("*a")
  f:close()
  return s
end

local function render(page)
  local level = 2
  while page:find("]" .. string.rep("=", level) .. "]", 1, true) do
    level = level + 1
  end
  local eq = string.rep("=", level)
  return string.format(HEADER, "%s") .. "return [" .. eq .. "[\n" .. page .. "]" .. eq .. "]\n"
end

local check = arg[1] == "--check"
local stale = {}
for _, p in ipairs(PAGES) do
  local source = p.dir .. "/" .. (p.page or "www/app/index.html")
  local page = read(source)
  local out = render(page):gsub("%%s", source, 1)
  local current
  local f = io.open(p.module, "rb")
  if f then
    current = f:read("*a")
    f:close()
  end
  if current ~= out then
    if check then
      stale[#stale + 1] = p.module
    else
      local w = assert(io.open(p.module, "wb"))
      w:write(out)
      w:close()
      print("wrote " .. p.module)
    end
  end
end
if #stale > 0 then
  io.stderr:write("stale page module(s): " .. table.concat(stale, ", ") .. " -- run `make embed-pages`\n")
  os.exit(1)
end
