  flood_warning = function(now)
    return {
      obs = obs(now, { textDescription = "Heavy Rain", humidity = 98, flags = { rain = true } }),
      alerts = { capAlert(now, "Flood Warning", "Severe") },
    }
  end,
  hurricane_warning = function(now)
    return {
      obs = obs(now, {
        textDescription = "Tropical Storm Conditions",
        windMph = 65,
        gustMph = 90,
        pressureInHg = 28.5,
        flags = { rain = true },
      }),
      alerts = { capAlert(now, "Hurricane Warning", "Extreme") },
    }
  end,
}

