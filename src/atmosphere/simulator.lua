--[[==========================================================================
  Atmosphere — simulation scenarios

  A dealer must be able to test programming without waiting for weather
  (spec: mandatory). Each scenario yields a synthetic normalized observation
  and/or CAP alert set that is fed into THE SAME engine.step() path as live
  data — the only difference is the simulation flag riding the snapshot.

  Alert scenarios go through walerts.normalize like real CAP payloads, so a
  simulated Tornado Warning exercises classification, admission filters,
  reconcile, and event mapping identically to a real one.
============================================================================]]

local walerts = require("atmosphere.alerts")

local M = {}

local function obs(now, over)
  local o = {
    timestamp = now,
    station = "SIMULATED",
    textDescription = "Simulated",
    tempC = 21,
    tempF = 70,
    feelsLikeF = 70,
    feelsLikeC = 21,
    humidity = 45,
    windMph = 5,
    gustMph = nil,
    windDeg = 180,
    windCompass = "S",
    pressureInHg = 29.92,
    pressurePa = 101325,
    visibilityMi = 10,
    visibilityM = 16093,
    cloudCover = 5,
    flags = { rain = false, snow = false, thunder = false, fog = false, ice = false, clear = true, cloudy = false },
  }
  for k, v in pairs(over or {}) do
    o[k] = v
  end
  return o
end

local function capAlert(now, event, severity, over)
  local raw = {
    id = "urn:oid:simulated." .. event:gsub("%W", "-"):lower(),
    event = event,
    headline = "SIMULATED: " .. event,
    severity = severity,
    certainty = "Observed",
    urgency = "Immediate",
    status = "Actual",
    messageType = "Alert",
    sent = now,
    senderName = "Atmosphere Simulator",
    areaDesc = "This property (simulated)",
    description = "This is a simulated " .. event .. " generated by SmartBuildOS Atmosphere for programming tests.",
    instruction = "No action required. This is a simulation.",
    response = "None",
  }
  for k, v in pairs(over or {}) do
    raw[k] = v
  end
  local a = walerts.normalize(raw)
  -- Times as epochs, filled directly (normalize parses strings; simulation
  -- supplies epochs so scenarios need no date formatting).
  a.effective = now
  a.onset = now
  a.expires = now + 2 * 3600
  a.ends = now + 2 * 3600
  return a
end

--- Scenario table: key -> function(now) -> { obs = ..., alerts = {...} }.
--- An absent obs means "keep current conditions, add the alerts".
M.SCENARIOS = {
  clear = function(now)
    return { obs = obs(now, {}), alerts = {} }
  end,
  cloudy = function(now)
    return {
      obs = obs(now, { textDescription = "Overcast", cloudCover = 95, flags = { cloudy = true } }),
      alerts = {},
