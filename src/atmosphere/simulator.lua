    }
  end,
  tornado_watch = function(now)
    return { alerts = { capAlert(now, "Tornado Watch", "Severe") } }
  end,
  tornado_warning = function(now)
    return {
      obs = obs(now, {
        textDescription = "Thunderstorm",
        windMph = 35,
        gustMph = 60,
        cloudCover = 100,
        flags = { rain = true, thunder = true },
      }),
      alerts = { capAlert(now, "Tornado Warning", "Extreme") },
    }
  end,
  severe_thunderstorm_warning = function(now)
    return {
      obs = obs(now, {
        textDescription = "Thunderstorm",
        windMph = 30,
        gustMph = 55,
        flags = { rain = true, thunder = true },
      }),
      alerts = { capAlert(now, "Severe Thunderstorm Warning", "Severe") },
    }
