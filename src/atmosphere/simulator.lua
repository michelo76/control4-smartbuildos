--- Builds a scenario. Returns { obs?, alerts = {...} } or nil for unknown.
function M.build(name, now)
  local f = M.SCENARIOS[tostring(name or ""):lower():gsub(" ", "_")]
  if f == nil then
    return nil
  end
  return f(now)
end

return M
