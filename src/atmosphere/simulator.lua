  end,
  heavy_rain = function(now)
    return {
      obs = obs(now, {
        textDescription = "Heavy Rain",
        cloudCover = 100,
        humidity = 95,
        visibilityMi = 1.5,
        windMph = 18,
        flags = { rain = true },
      }),
      alerts = {},
    }
  end,
  thunderstorm = function(now)
    return {
      obs = obs(now, {
        textDescription = "Thunderstorm",
        cloudCover = 100,
        windMph = 22,
        gustMph = 38,
        flags = { rain = true, thunder = true },
      }),
      alerts = {},
    }
  end,
  high_wind = function(now)
    return { obs = obs(now, { textDescription = "Windy", windMph = 28, gustMph = 40 }), alerts = {} }
  end,
  dangerous_wind = function(now)
    return { obs = obs(now, { textDescription = "Damaging Winds", windMph = 45, gustMph = 60 }), alerts = {} }
  end,
  freeze = function(now)
    return {
      obs = obs(now, { textDescription = "Clear and Cold", tempF = 28, tempC = -2.2, feelsLikeF = 22 }),
      alerts = {},
    }
  end,
  extreme_heat = function(now)
    return {
      obs = obs(now, { textDescription = "Hot", tempF = 101, tempC = 38.3, feelsLikeF = 108, humidity = 60 }),
      alerts = {},
    }
  end,
  snow = function(now)
    return {
      obs = obs(now, {
        textDescription = "Snow",
        tempF = 30,
        tempC = -1.1,
        cloudCover = 100,
        visibilityMi = 0.8,
        flags = { snow = true },
      }),
      alerts = {},
